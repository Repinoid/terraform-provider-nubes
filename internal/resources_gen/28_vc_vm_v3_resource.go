func (r *VcVmV3Resource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan VcVmV3Model
	var state VcVmV3Model
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	instanceID := state.ID
	if instanceID.IsNull() || instanceID.IsUnknown() {
		instanceID = plan.ID
	}
	if instanceID.IsNull() || instanceID.IsUnknown() {
		resp.Diagnostics.AddError("Ошибка клиента", "отсутствует идентификатор экземпляра для modify")
		return
	}

	hasServiceParamChanges := false
	if !hasServiceParamChanges {
		if plan.VmCpu.IsNull() != state.VmCpu.IsNull() || plan.VmCpu.IsUnknown() != state.VmCpu.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.VmCpu.IsNull() && !plan.VmCpu.IsUnknown() && !state.VmCpu.IsNull() && !state.VmCpu.IsUnknown() {
			if plan.VmCpu.ValueInt64() != state.VmCpu.ValueInt64() {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.VmRam.IsNull() != state.VmRam.IsNull() || plan.VmRam.IsUnknown() != state.VmRam.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.VmRam.IsNull() && !plan.VmRam.IsUnknown() && !state.VmRam.IsNull() && !state.VmRam.IsUnknown() {
			if plan.VmRam.ValueInt64() != state.VmRam.ValueInt64() {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.VmDisk.IsNull() != state.VmDisk.IsNull() || plan.VmDisk.IsUnknown() != state.VmDisk.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.VmDisk.IsNull() && !plan.VmDisk.IsUnknown() && !state.VmDisk.IsNull() && !state.VmDisk.IsUnknown() {
			if plan.VmDisk.ValueInt64() != state.VmDisk.ValueInt64() {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.IpSpaceName.IsNull() != state.IpSpaceName.IsNull() || plan.IpSpaceName.IsUnknown() != state.IpSpaceName.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.IpSpaceName.IsNull() && !plan.IpSpaceName.IsUnknown() && !state.IpSpaceName.IsNull() && !state.IpSpaceName.IsUnknown() {
			if !strings.EqualFold(plan.IpSpaceName.ValueString(), state.IpSpaceName.ValueString()) {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.AccessIpList.IsNull() != state.AccessIpList.IsNull() || plan.AccessIpList.IsUnknown() != state.AccessIpList.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.AccessIpList.IsNull() && !plan.AccessIpList.IsUnknown() && !state.AccessIpList.IsNull() && !state.AccessIpList.IsUnknown() {
			if !strings.EqualFold(plan.AccessIpList.ValueString(), state.AccessIpList.ValueString()) {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.AccessPortList.IsNull() != state.AccessPortList.IsNull() || plan.AccessPortList.IsUnknown() != state.AccessPortList.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.AccessPortList.IsNull() && !plan.AccessPortList.IsUnknown() && !state.AccessPortList.IsNull() && !state.AccessPortList.IsUnknown() {
			if !strings.EqualFold(plan.AccessPortList.ValueString(), state.AccessPortList.ValueString()) {
				hasServiceParamChanges = true
			}
		}
	}
	if !hasServiceParamChanges {
		if plan.SameSnat.IsNull() != state.SameSnat.IsNull() || plan.SameSnat.IsUnknown() != state.SameSnat.IsUnknown() {
			hasServiceParamChanges = true
		} else if !plan.SameSnat.IsNull() && !plan.SameSnat.IsUnknown() && !state.SameSnat.IsNull() && !state.SameSnat.IsUnknown() {
			if plan.SameSnat.ValueBool() != state.SameSnat.ValueBool() {
				hasServiceParamChanges = true
			}
		}
	}
	// --- Redeploy support (ARCHITECTURE.md) ---
	// Проверяем изменился ли git_revision.
	// Если да — вызываем redeploy вместо modify.
	// git_revision = "" (не задано) → обычный modify.
	redeployRequested := false
	if !plan.GitRevision.IsNull() && !plan.GitRevision.IsUnknown() {
		if state.GitRevision.IsNull() || state.GitRevision.IsUnknown() || plan.GitRevision.ValueString() != state.GitRevision.ValueString() {
			redeployRequested = true
		}
	}
	// ReconcileTrigger — дополнение к modify, а не его замена.
	// Учитываем и установку, и изменение, и очистку значения; неизвестное
	// плановое значение не считается подтверждённым запросом на операцию.
	reconcileRequested := false
	if !plan.ReconcileTrigger.IsUnknown() {
		if state.ReconcileTrigger.IsUnknown() || plan.ReconcileTrigger.IsNull() != state.ReconcileTrigger.IsNull() {
			reconcileRequested = true
		} else if !plan.ReconcileTrigger.IsNull() && plan.ReconcileTrigger.ValueString() != state.ReconcileTrigger.ValueString() {
			reconcileRequested = true
		}
	}

	if !hasServiceParamChanges && !redeployRequested && !reconcileRequested {
		// Сервисные параметры не изменились → modify НЕ вызываем.
		//
		// НО read-back поля (state_params*, state_out*, vault_*) обязаны быть
		// перечитаны из инстанса. Раньше здесь слепо копировались значения из
		// старого state, из-за чего tfstate хранил устаревшее значение:
		// пример — state_params["needEnableAVI"]="false", когда на платформе уже
		// true (модификатор включил ALB). Это давало ложный дрейф
		// «Objects have changed outside of Terraform» на каждом plan.
		plan.ID = instanceID
		refreshed, refreshDiags := resources_core.RefreshResourceState(ctx, r.client, instanceID.ValueString(), 28, plan, []resources_core.StateField{
			{Code: "state_params"},
			{Code: "state_out"},
			{Code: "state_params_flat"},
			{Code: "state_out_flat"},
			{Code: "vault_secrets"},
			{Code: "vault_url"},
			{Code: "vault_user_path"},
			{Code: "vault_fields"},
		}, []resources_core.InputField{
			{Code: "accessIpList", Field: "AccessIpList", Type: "string"},
			{Code: "accessPortList", Field: "AccessPortList", Type: "array-map-fixed"},
			{Code: "cloudInit", Field: "CloudInit", Type: "string"},
			{Code: "imageVm", Field: "ImageVm", Type: "string"},
			{Code: "ipSpaceName", Field: "IpSpaceName", Type: "string"},
			{Code: "sameSnat", Field: "SameSnat", Type: "bool"},
			{Code: "userLogin", Field: "UserLogin", Type: "string"},
			{Code: "userPublicKey", Field: "UserPublicKey", Type: "string"},
			{Code: "vmCpu", Field: "VmCpu", Type: "int64"},
			{Code: "vmDisk", Field: "VmDisk", Type: "int64"},
			{Code: "vmName", Field: "VmName", Type: "string"},
			{Code: "vmRam", Field: "VmRam", Type: "int64"},
		})
		resp.Diagnostics.Append(refreshDiags...)
		if resp.Diagnostics.HasError() {
			return
		}
		resp.Diagnostics.Append(resp.State.Set(ctx, &refreshed)...)
		return
	}

	operationTimeout := ""
	if !plan.OperationTimeout.IsNull() && !plan.OperationTimeout.IsUnknown() {
		operationTimeout = plan.OperationTimeout.ValueString()
	}
	if !plan.LogLevel.IsNull() && !plan.LogLevel.IsUnknown() {
		ctx = core.CtxWithLogLevel(ctx, plan.LogLevel.ValueString())
	}
	// Обычные параметры всегда применяются раньше дополнительных операций.
	// Если изменился только триггер, операция UpdateResource не вызывается.
	if hasServiceParamChanges {
		params := map[int]string{
			493:  resources_core.FormatInt64(plan.VmCpu),
			494:  resources_core.FormatInt64(plan.VmRam),
			495:  resources_core.FormatInt64(plan.VmDisk),
			496:  resources_core.FormatString(plan.IpSpaceName),
			497:  resources_core.FormatString(plan.AccessIpList),
			498:  resources_core.FormatString(plan.AccessPortList),
			1119: resources_core.FormatBool(plan.SameSnat),
		}
		if err := resources_core.UpdateResourceWithTimeout(ctx, r.client, instanceID.ValueString(), params, operationTimeout); err != nil {
			resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
			return
		}
	}
	// 2. Redeploy — только если изменился git_revision
	if redeployRequested {
		redeployParams := map[int]string{}
		redeployParams[509] = resources_core.FormatString(plan.VmName)
		redeployParams[510] = resources_core.FormatInt64(plan.VmCpu)
		redeployParams[511] = resources_core.FormatInt64(plan.VmRam)
		redeployParams[512] = resources_core.FormatInt64(plan.VmDisk)
		redeployParams[513] = resources_core.FormatString(plan.IpSpaceName)
		redeployParams[514] = resources_core.FormatString(plan.AccessIpList)
		redeployParams[515] = resources_core.FormatString(plan.ImageVm)
		redeployParams[516] = resources_core.FormatString(plan.UserLogin)
		redeployParams[517] = resources_core.FormatString(plan.UserPublicKey)
		redeployParams[518] = resources_core.FormatString(plan.CloudInit)
		redeployParams[520] = resources_core.FormatString(plan.AccessPortList)
		redeployParams[1123] = resources_core.FormatBool(plan.SameSnat)
		if err := r.client.RunRedeployOperation(ctx, instanceID.ValueString(), operationTimeout, redeployParams); err != nil {
			resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
			return
		}
	}
	// 3. Reconcile выполняется после modify и redeploy. Проверку availableOperations
	// и ожидание текущей операции выполняет общий helper; при ошибке новая модель
	// не записывается в state, поэтому триггер можно повторно применить.
	if reconcileRequested {
		if err := resources_core.RunOperationByCodeWithTimeout(ctx, r.client, instanceID.ValueString(), "reconcile", map[string]string{}, operationTimeout); err != nil {
			resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
			return
		}
	}

	plan.ID = instanceID
	state, diags := resources_core.RefreshResourceState(ctx, r.client, instanceID.ValueString(), 28, plan, []resources_core.StateField{
		{Code: "state_params"},
		{Code: "state_out"},
		{Code: "state_params_flat"},
		{Code: "state_out_flat"},
		{Code: "vault_secrets"},
		{Code: "vault_url"},
		{Code: "vault_user_path"},
		{Code: "vault_fields"},
	}, []resources_core.InputField{
		{Code: "accessIpList", Field: "AccessIpList", Type: "string"},
		{Code: "accessPortList", Field: "AccessPortList", Type: "array-map-fixed"},
		{Code: "cloudInit", Field: "CloudInit", Type: "string"},
		{Code: "imageVm", Field: "ImageVm", Type: "string"},
		{Code: "ipSpaceName", Field: "IpSpaceName", Type: "string"},
		{Code: "sameSnat", Field: "SameSnat", Type: "bool"},
		{Code: "userLogin", Field: "UserLogin", Type: "string"},
		{Code: "userPublicKey", Field: "UserPublicKey", Type: "string"},
		{Code: "vmCpu", Field: "VmCpu", Type: "int64"},
		{Code: "vmDisk", Field: "VmDisk", Type: "int64"},
		{Code: "vmName", Field: "VmName", Type: "string"},
		{Code: "vmRam", Field: "VmRam", Type: "int64"},
	})
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *VcVmV3Resource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state VcVmV3Model
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if state.ID.IsNull() || state.ID.IsUnknown() {
		return
	}

	deleteMode := "delete"
	if !state.SuspendOnDestroy.IsNull() && !state.SuspendOnDestroy.IsUnknown() && state.SuspendOnDestroy.ValueBool() {
		deleteMode = "suspend"
	}
	if !state.KeepOnDestroy.IsNull() && !state.KeepOnDestroy.IsUnknown() && state.KeepOnDestroy.ValueBool() {
		deleteMode = "state_only"
	}

	operationTimeout := ""
	if !state.OperationTimeout.IsNull() && !state.OperationTimeout.IsUnknown() {
		operationTimeout = state.OperationTimeout.ValueString()
	}
	if !state.LogLevel.IsNull() && !state.LogLevel.IsUnknown() {
		ctx = core.CtxWithLogLevel(ctx, state.LogLevel.ValueString())
	}
	if err := resources_core.DeleteResourceWithTimeout(ctx, r.client, state.ID.ValueString(), deleteMode, operationTimeout); err != nil {
		resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
		return
	}

	switch deleteMode {
	case "suspend":
		resp.Diagnostics.AddWarning(
			"Ресурс заморожен, а не удалён",
			"destroy: vc_vm_v3 (service_id=28) переведён в suspend, удаление не выполнялось. Для полного удаления выставьте suspend_on_destroy = false.",
		)
	case "state_only":
		resp.Diagnostics.AddWarning(
			"Ресурс оставлен как есть, а не удалён",
			"destroy: vc_vm_v3 (service_id=28) не изменялся в облаке и только убран из состояния (keep_on_destroy = true). Для полного удаления выставьте keep_on_destroy = false.",
		)
	}
}

