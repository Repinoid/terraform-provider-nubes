func (r *PostgresResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan PostgresModel
	var state PostgresModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}

	instanceID := state.ID
	if instanceID.IsNull() || instanceID.IsUnknown() {
		instanceID = plan.ID
	}
	if instanceID.IsNull() || instanceID.IsUnknown() {
		resp.Diagnostics.AddError("Ошибка клиента", "отсутствует идентификатор экземпляра для modify")
		return
	}

	hasServiceParamChanges := false
	// ReconcileTrigger — дополнение к modify, а не его замена.
	// Учитываем и установку, и изменение, и очистку значения; неизвестное
	// плановое значение не считается подтверждённым запросом на операцию.
	reconcileRequested := false
	if !plan.ReconcileTrigger.IsUnknown() {
		if state.ReconcileTrigger.IsUnknown() || plan.ReconcileTrigger.IsNull() != state.ReconcileTrigger.IsNull() {
			reconcileRequested = true
		} else if !plan.ReconcileTrigger.IsNull() && plan.ReconcileTrigger.ValueString() != state.ReconcileTrigger.ValueString() {
			reconcileRequested = true
		}
	}

	if !hasServiceParamChanges && !reconcileRequested {
		// Сервисные параметры не изменились → modify НЕ вызываем.
		//
		// НО read-back поля (state_params*, state_out*, vault_*) обязаны быть
		// перечитаны из инстанса. Раньше здесь слепо копировались значения из
		// старого state, из-за чего tfstate хранил устаревшее значение:
		// пример — state_params["needEnableAVI"]="false", когда на платформе уже
		// true (модификатор включил ALB). Это давало ложный дрейф
		// «Objects have changed outside of Terraform» на каждом plan.
		plan.ID = instanceID
		refreshed, refreshDiags := resources_core.RefreshResourceState(ctx, r.client, instanceID.ValueString(), 90, plan, []resources_core.StateField{
			{Code: "state_params"},
			{Code: "state_out"},
			{Code: "state_params_flat"},
			{Code: "state_out_flat"},
			{Code: "vault_secrets"},
			{Code: "vault_url"},
			{Code: "vault_user_path"},
			{Code: "vault_fields"},
		}, []resources_core.InputField{
			{Code: "accessConfiguration", Field: "AccessConfiguration", Type: "map-fixed"},
			{Code: "autoscaleConfiguration", Field: "AutoscaleConfiguration", Type: "map-fixed"},
			{Code: "backupConfiguration", Field: "BackupConfiguration", Type: "map-fixed"},
			{Code: "clusterConfiguration", Field: "ClusterConfiguration", Type: "map-fixed"},
			{Code: "mtlsConfiguration", Field: "MtlsConfiguration", Type: "map-fixed"},
			{Code: "postgresConf", Field: "PostgresConf", Type: "map-fixed"},
			{Code: "postgresConfiguration", Field: "PostgresConfiguration", Type: "map-fixed"},
			{Code: "startupConfiguration", Field: "StartupConfiguration", Type: "map-fixed"},
		})
		resp.Diagnostics.Append(refreshDiags...)
		if resp.Diagnostics.HasError() {
			return
		}
		resp.Diagnostics.Append(resp.State.Set(ctx, &refreshed)...)
		return
	}

	operationTimeout := ""
	if !plan.OperationTimeout.IsNull() && !plan.OperationTimeout.IsUnknown() {
		operationTimeout = plan.OperationTimeout.ValueString()
	}
	if !plan.LogLevel.IsNull() && !plan.LogLevel.IsUnknown() {
		ctx = core.CtxWithLogLevel(ctx, plan.LogLevel.ValueString())
	}
	// Обычные параметры всегда применяются раньше дополнительных операций.
	// Если изменился только триггер, операция UpdateResource не вызывается.
	if hasServiceParamChanges {
		params := map[int]string{}
		if plan.ClusterConfiguration != nil {
			params[795] = resources_core.BuildJSON(map[string]string{"cpu": fmt.Sprintf("%d", plan.ClusterConfiguration.Cpu.ValueInt64()), "memory": fmt.Sprintf("%d", plan.ClusterConfiguration.Memory.ValueInt64()), "replicas": fmt.Sprintf("%d", plan.ClusterConfiguration.Replicas.ValueInt64()), "disk": fmt.Sprintf("%d", plan.ClusterConfiguration.Disk.ValueInt64())})
		}
		if plan.AccessConfiguration != nil {
			params[796] = resources_core.BuildJSON(map[string]string{"masterIpSpace": fmt.Sprintf("\"%s\"", plan.AccessConfiguration.MasterIpSpace.ValueString()), "masterAccessList": plan.AccessConfiguration.MasterAccessList.ValueString(), "slaveIpSpace": fmt.Sprintf("\"%s\"", plan.AccessConfiguration.SlaveIpSpace.ValueString()), "slaveAccessList": plan.AccessConfiguration.SlaveAccessList.ValueString()})
		}
		if plan.PostgresConfiguration != nil {
			params[797] = resources_core.BuildJSON(map[string]string{"version": fmt.Sprintf("\"%s\"", plan.PostgresConfiguration.Version.ValueString()), "sslRequired": fmt.Sprintf("%v", plan.PostgresConfiguration.SslRequired.ValueBool()), "poolerMaster": fmt.Sprintf("%v", plan.PostgresConfiguration.PoolerMaster.ValueBool()), "poolerSlave": fmt.Sprintf("%v", plan.PostgresConfiguration.PoolerSlave.ValueBool())})
		}
		if plan.PostgresConf != nil {
			params[798] = resources_core.BuildJSON(map[string]string{"log_connections": fmt.Sprintf("\"%s\"", plan.PostgresConf.LogConnections.ValueString()), "log_disconnections": fmt.Sprintf("\"%s\"", plan.PostgresConf.LogDisconnections.ValueString()), "max_connections": fmt.Sprintf("%d", plan.PostgresConf.MaxConnections.ValueInt64())})
		}
		if plan.BackupConfiguration != nil {
			params[799] = resources_core.BuildJSON(map[string]string{"retain": fmt.Sprintf("%d", plan.BackupConfiguration.Retain.ValueInt64()), "schedule": fmt.Sprintf("\"%s\"", plan.BackupConfiguration.Schedule.ValueString()), "s3Uid": fmt.Sprintf("\"%s\"", plan.BackupConfiguration.S3Uid.ValueString()), "incrementCount": fmt.Sprintf("%d", plan.BackupConfiguration.IncrementCount.ValueInt64())})
		}
		if plan.AutoscaleConfiguration != nil {
			params[800] = resources_core.BuildJSON(map[string]string{"enabled": fmt.Sprintf("%v", plan.AutoscaleConfiguration.Enabled.ValueBool()), "schedule": fmt.Sprintf("%d", plan.AutoscaleConfiguration.Schedule.ValueInt64()), "quota": fmt.Sprintf("%d", plan.AutoscaleConfiguration.Quota.ValueInt64()), "percent": fmt.Sprintf("%d", plan.AutoscaleConfiguration.Percent.ValueInt64())})
		}
		if plan.MtlsConfiguration != nil {
			params[1095] = resources_core.BuildJSON(map[string]string{"type": fmt.Sprintf("\"%s\"", plan.MtlsConfiguration.Type.ValueString()), "durationCA": fmt.Sprintf("%d", plan.MtlsConfiguration.DurationCA.ValueInt64()), "durationServer": fmt.Sprintf("%d", plan.MtlsConfiguration.DurationServer.ValueInt64()), "certCA": fmt.Sprintf("\"%s\"", plan.MtlsConfiguration.CertCA.ValueString()), "certServer": fmt.Sprintf("\"%s\"", plan.MtlsConfiguration.CertServer.ValueString()), "refreshCert": fmt.Sprintf("%v", plan.MtlsConfiguration.RefreshCert.ValueBool())})
		}
		if err := resources_core.UpdateResourceWithTimeout(ctx, r.client, instanceID.ValueString(), params, operationTimeout); err != nil {
			resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
			return
		}
	}
	// 3. Reconcile выполняется после modify и redeploy. Проверку availableOperations
	// и ожидание текущей операции выполняет общий helper; при ошибке новая модель
	// не записывается в state, поэтому триггер можно повторно применить.
	if reconcileRequested {
		if err := resources_core.RunOperationByCodeWithTimeout(ctx, r.client, instanceID.ValueString(), "reconcile", map[string]string{}, operationTimeout); err != nil {
			resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
			return
		}
	}

	plan.ID = instanceID
	state, diags := resources_core.RefreshResourceState(ctx, r.client, instanceID.ValueString(), 90, plan, []resources_core.StateField{
		{Code: "state_params"},
		{Code: "state_out"},
		{Code: "state_params_flat"},
		{Code: "state_out_flat"},
		{Code: "vault_secrets"},
		{Code: "vault_url"},
		{Code: "vault_user_path"},
		{Code: "vault_fields"},
	}, []resources_core.InputField{
		{Code: "accessConfiguration", Field: "AccessConfiguration", Type: "map-fixed"},
		{Code: "autoscaleConfiguration", Field: "AutoscaleConfiguration", Type: "map-fixed"},
		{Code: "backupConfiguration", Field: "BackupConfiguration", Type: "map-fixed"},
		{Code: "clusterConfiguration", Field: "ClusterConfiguration", Type: "map-fixed"},
		{Code: "mtlsConfiguration", Field: "MtlsConfiguration", Type: "map-fixed"},
		{Code: "postgresConf", Field: "PostgresConf", Type: "map-fixed"},
		{Code: "postgresConfiguration", Field: "PostgresConfiguration", Type: "map-fixed"},
		{Code: "startupConfiguration", Field: "StartupConfiguration", Type: "map-fixed"},
	})
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

func (r *PostgresResource) Delete(ctx context.Context, req resource.DeleteRequest, resp *resource.DeleteResponse) {
	var state PostgresModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)
	if resp.Diagnostics.HasError() {
		return
	}
	if state.ID.IsNull() || state.ID.IsUnknown() {
		return
	}

	deleteMode := "delete"
	if !state.SuspendOnDestroy.IsNull() && !state.SuspendOnDestroy.IsUnknown() && state.SuspendOnDestroy.ValueBool() {
		deleteMode = "suspend"
	}
	if !state.KeepOnDestroy.IsNull() && !state.KeepOnDestroy.IsUnknown() && state.KeepOnDestroy.ValueBool() {
		deleteMode = "state_only"
	}

	operationTimeout := ""
	if !state.OperationTimeout.IsNull() && !state.OperationTimeout.IsUnknown() {
		operationTimeout = state.OperationTimeout.ValueString()
	}
	if !state.LogLevel.IsNull() && !state.LogLevel.IsUnknown() {
		ctx = core.CtxWithLogLevel(ctx, state.LogLevel.ValueString())
	}
	if err := resources_core.DeleteResourceWithTimeout(ctx, r.client, state.ID.ValueString(), deleteMode, operationTimeout); err != nil {
		resp.Diagnostics.AddError(resources_core.ErrorSummary(err), err.Error())
		return
	}

	switch deleteMode {
	case "suspend":
		resp.Diagnostics.AddWarning(
			"Ресурс заморожен, а не удалён",
			"destroy: postgres (service_id=90) переведён в suspend, удаление не выполнялось. Для полного удаления выставьте suspend_on_destroy = false.",
		)
	case "state_only":
		resp.Diagnostics.AddWarning(
			"Ресурс оставлен как есть, а не удалён",
			"destroy: postgres (service_id=90) не изменялся в облаке и только убран из состояния (keep_on_destroy = true). Для полного удаления выставьте keep_on_destroy = false.",
		)
	}
}

